// bun src/clips.ts list | stale [days] | ids [series] | index | path <name> <format>
// The index of every series clip: what exists, how old its facts are, and where the files are.
import { existsSync, mkdirSync } from "node:fs";
import { SERIES } from "../clips/index.ts";
import { clipId, explainer } from "./kits/explainer.ts";
import { ageInDays, expand } from "./kits/series.ts";
import { loadFilm, videoPath, type FormatName } from "./lib/film.ts";

const [cmd = "list", arg, arg2] = process.argv.slice(2);
const today = new Date();
const clips = SERIES.flatMap(expand);
const count = (s: (typeof SERIES)[number], status: string): number => s.clips.filter((c) => c.status === status).length;

if (cmd === "list") {
  for (const s of SERIES) {
    console.log(`\n${s.service} (${s.code}): ${count(s, "made")} made, ${count(s, "draft")} draft, ${s.planned?.length ?? 0} planned`);
    const rows = [
      ...expand(s).map((c) => ({ n: c.number, text: `${clipId(c).padEnd(38)} ${c.status.padEnd(6)} checked ${c.checked} (${ageInDays(c, today)}d)` })),
      ...(s.planned ?? []).map((p) => ({ n: p.number, text: `${`${s.code}-${String(p.number).padStart(2, "0")}-${p.slug}`.padEnd(38)} planned` })),
    ].sort((a, b) => a.n - b.n);
    for (const r of rows) console.log(`  ${r.text}`);
  }
} else if (cmd === "ids") {
  // one id per line, for shell loops; drafts are left out so they are never batch-rendered for posting
  for (const c of clips) if ((!arg || c.series === arg) && c.status === "made") console.log(clipId(c));
} else if (cmd === "stale") {
  // AWS changes limits, defaults and prices: anything older than this needs its sources re-read
  const limit = Number(arg ?? 180);
  const old = clips.filter((c) => ageInDays(c, today) > limit);
  for (const c of old) console.log(`${clipId(c)}  checked ${c.checked}, ${ageInDays(c, today)} days ago`);
  console.log(old.length ? `${old.length} clip(s) older than ${limit} days` : `nothing older than ${limit} days`);
  if (old.length) process.exit(1);
} else if (cmd === "path") {
  // where a film's finished file is, for `just open`
  if (!arg || !arg2) throw new Error("usage: bun src/clips.ts path <name> <format>");
  console.log(videoPath(await loadFilm(arg), arg2 as FormatName));
} else if (cmd === "index") {
  // videos/README.md: every finished clip, by series, with the files that exist for it
  const lines = ["# Videos", "", "> Generated by `just videos`. Finished, fact-checked clips, filed by service.", "> File names read `<clip>_<format>_<date facts were checked>.mp4`.", ""];
  for (const s of SERIES) {
    const made = expand(s).filter((c) => c.status === "made").sort((a, b) => a.number - b.number);
    if (!made.length) continue;
    lines.push(`## ${s.service}`, "", "| # | Clip | Checked | 4x5 | 9x16 | 16x9 |", "|---|---|---|---|---|---|");
    for (const c of made) {
      const film = await explainer(c);
      const cell = (f: FormatName): string => (existsSync(videoPath(film, f)) ? `[mp4](${videoPath(film, f).replace("videos/", "")})` : "not rendered");
      lines.push(`| ${c.number} | \`${clipId(c)}\` | ${c.checked} | ${cell("4x5")} | ${cell("9x16")} | ${cell("16x9")} |`);
    }
    lines.push("");
  }
  mkdirSync("videos", { recursive: true });
  await Bun.write("videos/README.md", `${lines.join("\n")}\n`);
  console.log("wrote videos/README.md");
} else {
  console.error("usage: bun src/clips.ts list | stale [days] | ids [series] | index | path <name> <format>");
  process.exit(2);
}
